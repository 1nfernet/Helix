"""The *compiler output* layer: a fully resolved, provenance-stamped design.

Everything here is machine-generated by the deterministic compiler. It is large,
detailed, and reproducible: given the same spec, the same adapters, and the same
adapter versions, ``ResolvedDesign`` is byte-stable (no wall-clock in the design
itself; the run timestamp lives in :class:`Provenance`).
"""

from __future__ import annotations

from typing import Dict, List, Optional

from pydantic import BaseModel, Field

from helix.ir.enums import Enzyme, Strand


class TargetLocus(BaseModel):
    """Genomic coordinates of the resolved edit window (from a gene database)."""

    chromosome: str
    start: int = Field(description="1-based genomic start of the window.")
    end: int = Field(description="1-based genomic end (inclusive).")
    strand: int = Field(description="+1 or -1; the window sequence is on this strand.")


class SeqVariant(BaseModel):
    """A known population variant, mapped to the target window (VariantProvider output)."""

    id: str
    window_pos: int = Field(description="0-based position in the target window.")
    alleles: str = ""
    frequency: Optional[float] = Field(default=None, description="Minor-allele frequency, if known.")


class VariantHit(BaseModel):
    """A known population variant overlapping a guide's protospacer/seed/PAM."""

    id: str
    window_pos: int = Field(description="0-based position in the target window.")
    region: str = Field(description="PAM / seed / protospacer.")
    alleles: str = ""
    frequency: Optional[float] = Field(default=None, description="Minor-allele frequency, if known.")


class ResolvedTarget(BaseModel):
    """The concrete edit window the guide designer operates on."""

    gene: str
    genome_build: str
    sequence: str = Field(description="Edit-window DNA, 5'->3', plus strand.")
    length: int
    source: str = Field(description="Adapter that produced this sequence.")
    locus: Optional[TargetLocus] = Field(default=None, description="Genomic coords when database-resolved.")
    frame: Optional[int] = Field(
        default=None, description="Reading-frame phase of window position 0 (0/1/2), if the target is coding."
    )


class OffTargetSite(BaseModel):
    sequence: str
    mismatches: int
    cfd: float = Field(ge=0.0, le=1.0, description="Cutting Frequency Determination score.")
    locus: Optional[str] = None


class OffTargetReport(BaseModel):
    max_cfd: float = Field(ge=0.0, le=1.0)
    site_count: int
    sites: List[OffTargetSite] = Field(default_factory=list)
    scorer: str


class RepairOutcome(BaseModel):
    """Predicted DSB-repair genotype distribution (the 'simulation' result)."""

    frameshift_fraction: float = Field(ge=0.0, le=1.0)
    top_outcomes: List[Dict[str, float]] = Field(
        default_factory=list,
        description="Ordered list of {edit_description: fraction}.",
    )
    predictor: str


class ProteinConsequence(BaseModel):
    """Effect of a DNA edit on the encoded protein (needs a reading frame)."""

    kind: str = Field(description="synonymous | missense | nonsense | stop-loss")
    ref_aa: str = Field(description="Reference amino acid (1-letter; '*' = stop).")
    alt_aa: str = Field(description="Edited amino acid (1-letter; '*' = stop).")
    codon_change: str = Field(description="e.g. 'CAG>TAG'.")
    label: str = Field(description="Human summary, e.g. 'Q>* premature stop', 'silent'.")
    note: str = Field("", description="Extra context, e.g. bystander consequences.")


class BaseEditOutcome(BaseModel):
    """Predicted base-editing result over the editing window."""

    editor: str  # CBE / ABE
    window: str = Field(description="Protospacer subsequence over the editing window.")
    window_abs_start: int = Field(0, description="0-based start of the editing window in the target sequence.")
    target_base: str
    product_base: str
    edited_positions: List[int] = Field(
        default_factory=list, description="1-based protospacer positions edited."
    )
    bystander_count: int = Field(0, description="Editable bases in the window beyond one.")
    edited_product: str = Field(description="The window after conversion.")
    efficiency: float = Field(ge=0.0, le=1.0, description="Predicted editing efficiency.")
    bystander_proportion: Optional[float] = Field(
        default=None, description="Predicted fraction of edits carrying bystander edits."
    )
    consequence: Optional[ProteinConsequence] = Field(
        default=None, description="Protein-level effect of the edited window (needs a frame)."
    )
    predictor: str


class HdrDonor(BaseModel):
    """A homology-directed-repair donor template for a knock-in guide."""

    donor_type: str  # ssODN / dsDNA
    strand: str = Field(description="Recommended ssODN strand ('+'/'-'); the non-target strand.")
    left_arm: str = Field(description="5' homology arm (genomic).")
    insert: str = Field(description="The installed payload (substituted/inserted bases; '' for a deletion).")
    right_arm: str = Field(description="3' homology arm (genomic).")
    sequence: str = Field(description="Full donor, 5'->3' (left_arm + insert + right_arm).")
    edit: str = Field(description="Human-readable edit, e.g. 'G>A @ 74', 'ins FLAG @ 40'.")
    edit_pos: int = Field(description="0-based edit position in the target window.")
    cut_to_edit_distance: int = Field(description="bp from the nuclease cut to the edit (HDR falls off with distance).")
    arm_length: int
    pam_disrupted: bool = Field(description="Whether re-cutting of the corrected allele is blocked.")
    recut_note: str = ""
    consequence: Optional[ProteinConsequence] = Field(
        default=None, description="Protein-level effect of the installed edit (needs a frame)."
    )
    silent_pam_block: Optional[bool] = Field(
        default=None, description="True/False when a frame is known: is the PAM-block mutation synonymous?"
    )


class RegulationOutcome(BaseModel):
    """CRISPRi/a guide placement relative to the transcription start site."""

    mode: str  # crispri / crispra
    tss_offset: int = Field(description="Signed bp from the TSS (− upstream, + downstream).")
    activity_score: float = Field(ge=0.0, le=1.0, description="Positional efficacy 0..1.")
    optimal: bool = Field(description="Whether the guide sits in the high-activity window.")


class ConstraintCheck(BaseModel):
    name: str
    passed: bool
    detail: str = ""


class GuideCandidate(BaseModel):
    """A single scored guide RNA, with all evidence attached."""

    spacer: str = Field(description="Protospacer, 5'->3', 20 nt for SpCas9.")
    pam: str
    strand: Strand
    window_offset: int = Field(description="0-based start within the edit window.")
    cut_site: int = Field(description="0-based cut position within the edit window.")
    gc_content: float
    self_complementarity: int = Field(0, description="Longest internal reverse-complementary stem (hairpin risk).")

    on_target_score: float = Field(ge=0.0, le=1.0)
    off_target: OffTargetReport
    repair: Optional[RepairOutcome] = None  # set for knockout
    base_edit: Optional[BaseEditOutcome] = None  # set for base editing
    hdr: Optional[HdrDonor] = None  # set for HDR knock-in
    regulation: Optional[RegulationOutcome] = None  # set for CRISPRi/a
    variant_hits: List["VariantHit"] = Field(default_factory=list, description="Population variants in the seed/PAM.")

    checks: List[ConstraintCheck] = Field(default_factory=list)
    passed: bool = False
    composite_score: float = 0.0
    rank: Optional[int] = None

    @property
    def failed_checks(self) -> List[str]:
        return [c.name for c in self.checks if not c.passed]


class ValidationPrimers(BaseModel):
    forward: str
    reverse: str
    amplicon_length: int
    note: str = ""


class Provenance(BaseModel):
    """Everything needed to reproduce or audit a run."""

    helix_version: str
    genome_build: str
    timestamp_utc: str
    adapters: Dict[str, str] = Field(
        default_factory=dict, description="registry_role -> 'name@version'."
    )
    spec_name: str


class SafetyVerdict(BaseModel):
    allowed: bool
    reasons: List[str] = Field(default_factory=list)
    screen_version: str


class DeliveryOption(BaseModel):
    method: str
    score: float = Field(ge=0.0, le=1.0, description="Suitability for this design/context.")
    rationale: str = ""
    warnings: List[str] = Field(default_factory=list)


class DeliveryRecommendation(BaseModel):
    recommended: str
    requested: Optional[str] = None
    requested_suitable: Optional[bool] = None
    cargo_kb: float = Field(description="Approximate editor coding size, kb.")
    context: str = Field(description="'in_vitro' or 'in_vivo' as inferred from the spec.")
    options: List[DeliveryOption] = Field(default_factory=list)
    notes: List[str] = Field(default_factory=list)


class DeletionPlan(BaseModel):
    """A dual-cut excision: the region removed between two flanking guides."""

    requested_span: str = Field(description="The requested delete span, e.g. '40..90' (1-based).")
    deletion_start: int = Field(description="0-based realized start (5' cut).")
    deletion_end: int = Field(description="0-based realized end (3' cut).")
    deletion_size: int = Field(description="bp removed between the cuts.")
    junction: str = Field(description="Sequence across the repair junction (…5' flank / 3' flank…).")
    left_cut: int
    right_cut: int


class PrimeEditCandidate(BaseModel):
    """A pegRNA design for a templated (prime) edit."""

    spacer: str = Field(description="Nicking-guide protospacer, 5'->3'.")
    pam: str
    strand: Strand
    nick_position: int = Field(description="0-based nick position within the window.")
    pbs: str = Field(description="Primer binding site (3' extension, binds the nicked strand).")
    rtt: str = Field(description="Reverse-transcriptase template encoding the edit.")
    peg_extension: str = Field(description="Full 3' extension appended to the spacer scaffold (RTT+PBS).")
    edit: str = Field(description="Human-readable edit, e.g. 'A>G @ 12', 'ins AAC', 'del AC'.")
    on_target_score: float = Field(ge=0.0, le=1.0)
    predicted_efficiency: float = Field(0.0, ge=0.0, le=1.0, description="Predicted PE efficiency.")
    predictor: str = ""
    pe3_nick_spacer: Optional[str] = Field(default=None, description="PE3 second-nick guide (opposite strand).")
    pe3_nick_position: Optional[int] = Field(default=None, description="PE3 nick position (window coord).")
    consequence: Optional[ProteinConsequence] = Field(
        default=None, description="Protein-level effect of the installed edit (needs a frame)."
    )
    checks: List[ConstraintCheck] = Field(default_factory=list)
    passed: bool = False
    composite_score: float = 0.0
    rank: Optional[int] = None


class ResolvedDesign(BaseModel):
    """The compiler's complete answer for one spec."""

    spec_name: str
    modality: str = "crispr_ko"
    resolved_enzyme: Enzyme
    target: Optional[ResolvedTarget] = Field(
        default=None, description="None if the run was blocked before target resolution."
    )

    guides: List[GuideCandidate] = Field(
        default_factory=list, description="Nuclease/base-edit candidates, ranked."
    )
    selected: List[GuideCandidate] = Field(
        default_factory=list, description="Top guides satisfying every constraint."
    )
    prime_edits: List[PrimeEditCandidate] = Field(
        default_factory=list, description="pegRNA candidates (prime editing), ranked."
    )
    feasible: bool = True
    infeasibility_notes: List[str] = Field(default_factory=list)

    validation_primers: Optional[ValidationPrimers] = None
    delivery: Optional[DeliveryRecommendation] = None
    deletion: Optional[DeletionPlan] = None  # set for dual-cut deletion
    safety: SafetyVerdict
    provenance: Provenance
